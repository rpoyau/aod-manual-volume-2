"""Persisted illustrative geometry/ledger controls; no physical admission claims."""
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'manual2/scripts'))
from matter1_folding import (ValidationError, build_event_ledger, canonical_bytes, check_fixture,
                            evaluate, read_json, validate_event_ledger, verify)

DATA = Path('manual2/data/m1/folding')
VERIFY = ROOT / 'manual2/scripts/verify_matter1_folding.py'
GENERATE = ROOT / 'manual2/scripts/generate_matter1_folding.py'


def snapshot(root):
    return {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob('*')) if p.is_file()}


class FoldingTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix='matter1-folding-test-')
        self.root = Path(self.temporary.name)
        shutil.copytree(ROOT / DATA, self.root / DATA)
        self.fixture = read_json(self.root / DATA / 'two_square_fold.json')
        self.ledger = read_json(self.root / DATA / 'event_ledger.json')

    def tearDown(self):
        self.temporary.cleanup()

    def cli(self, optimized=False, extra=()):
        return subprocess.run([sys.executable, '-B'] + (['-O'] if optimized else [])
                              + [str(VERIFY), '--root', str(self.root), *extra],
                              capture_output=True, text=True, timeout=30)

    def mutated_rejection(self, filename, mutate, reason):
        path = self.root / DATA / filename
        original = path.read_bytes()
        data = json.loads(original)
        mutate(data)
        path.write_bytes(canonical_bytes(data))
        frozen = snapshot(self.root)
        try:
            for optimized in (False, True):
                with self.subTest(optimized=optimized):
                    result = self.cli(optimized)
                    self.assertNotEqual(result.returncode, 0, result.stdout)
                    self.assertIn(reason, result.stderr)
                    self.assertEqual(snapshot(self.root), frozen, 'Verifier changed rejected data or added files')
        finally:
            path.write_bytes(original)

    def test_valid_persisted_contract_read_only(self):
        """P1-01/P1-05/P5-04: real file reader, both modes, no writes/new files."""
        frozen = snapshot(self.root)
        for optimized in (False, True):
            with self.subTest(optimized=optimized):
                result = self.cli(optimized, ('--check-data',))
                self.assertEqual(result.returncode, 0, result.stderr)
                report = json.loads(result.stdout)
                self.assertEqual(report['geometry']['distinct_q4_vertices'], 6)
                self.assertEqual(report['geometry']['shared_edge_outer_coefficient'], 0)
                self.assertEqual(report['events']['total_traversals'], 18)
                self.assertEqual(report['events']['outgoing_traversals'], 9)
                self.assertEqual(report['events']['returning_traversals'], 9)
                self.assertIsNone(report['events']['native_closure_count'])
                self.assertEqual(snapshot(self.root), frozen)

    def test_repetition_counts_come_from_external_events(self):
        """P1-05: validate actual event records for all 64 bounded repetition cases."""
        for n in range(1, 65):
            with self.subTest(n=n):
                ledger = build_event_ledger(self.fixture, n)
                # Treat generated bytes as an external serialized ledger, then reread.
                path = self.root / DATA / 'event_ledger.json'
                path.write_bytes(canonical_bytes(ledger))
                counts = validate_event_ledger(self.fixture, read_json(path))
                self.assertEqual(counts['outgoing_traversals'], 3*n)
                self.assertEqual(counts['returning_traversals'], 3*n)
                self.assertEqual(counts['distinct_event_ids'], 6*n)

    def test_coordinate_aliases_reject(self):
        """P1-01: exact E=D/F=C review mutation."""
        self.mutated_rejection('two_square_fold.json',
                               lambda f: f['vertices'].update(E='0100', F='1100'),
                               'Distinct used vertices must have distinct Q4 addresses')

    def test_wrong_interface_orientation_rejects(self):
        """P1-02: opposite oriented incidences are necessary for cancellation."""
        self.mutated_rejection('two_square_fold.json', lambda f: f['plus_face'].reverse(),
                               'Interface orientations do not cancel')

    def test_non_hamming_edge_rejects(self):
        """P1-03: Q4 support is checked on stored coordinates."""
        self.mutated_rejection('two_square_fold.json', lambda f: f['vertices'].update(E='0110'),
                               'Non-Hamming-1 edge')

    def test_missing_side_or_interface_rejects(self):
        """P1-04: all three sides/interface roles belong to declared geometry."""
        self.mutated_rejection('two_square_fold.json', lambda f: f['vertex_roles'].pop('E'),
                               'Incorrect or missing ternary vertex roles')
        self.mutated_rejection('two_square_fold.json', lambda f: f['shared_interface'].pop(),
                               'Invalid shared interface')

    def test_duplicate_identity_and_serialization_replay_reject(self):
        """P1-06: a new serialization label cannot duplicate a committed event."""
        def duplicate_id(ledger):
            ledger['events'][1]['event_id'] = ledger['events'][0]['event_id']
        self.mutated_rejection('event_ledger.json', duplicate_id, 'Duplicate or replayed event identity')
        def replay(ledger):
            ledger['events'][1] = deepcopy(ledger['events'][0])
            ledger['events'][1]['record_id'] = 'new-serialization-of-old-event'
        self.mutated_rejection('event_ledger.json', replay, 'Duplicate or replayed event identity')
        self.mutated_rejection('event_ledger.json',
                               lambda f: f['events'][1].update(record_id=f['events'][0]['record_id']),
                               'Duplicate serialization record')

    def test_wrong_scope_lineage_and_fixture_bindings_reject(self):
        """P1-06: event positions and source bindings remain scoped."""
        for field in ('scope_id', 'lineage_id'):
            self.mutated_rejection('event_ledger.json', lambda f, k=field: f['events'][2].update({k: 'substitute'}),
                                   'Wrong event scope/lineage/resolution binding')
        self.mutated_rejection('event_ledger.json', lambda f: f.update(fixture_binding='forged'),
                               'Wrong fixture binding')
        self.mutated_rejection('event_ledger.json', lambda f: f['scope'].update(resolution=1),
                               'Wrong ledger scope/lineage')

    def test_predecessor_ordinals_and_occurrences_reject(self):
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][1].update(predecessor_event_id='unknown'),
                               'Wrong retained event predecessor')
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][1].update(ordinal=1),
                               'Wrong committed ordinal')
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][6].update(repetition=0),
                               'Wrong traversal occurrence binding')

    def test_role_names_do_not_determine_ticks(self):
        """P1-07: removing events or using role names does not count traversals."""
        self.mutated_rejection('event_ledger.json', lambda f: f.update(event_unit='three_ternary_roles'),
                               'Role names or support weights are not event ticks')
        self.mutated_rejection('event_ledger.json', lambda f: f['events'].pop(),
                               'Ledger event count must equal six times repetitions')

    def test_hinge_support_is_not_an_extra_edge(self):
        """P1-08: unit hinge support is not silently inserted as H1 traversal."""
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][2].update(kind='unit_hinge_support'),
                               'A support weight or sample is not an H1 traversal')
        self.mutated_rejection('event_ledger.json', lambda f: f['events'].append(deepcopy(f['events'][-1])),
                               'Ledger event count must equal six times repetitions')

    def test_hamming_witnesses_are_checked(self):
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][0].update(changed_coordinate=0),
                               'Wrong changed-coordinate witness')
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][0].update(target_address='1111'),
                               'Wrong coordinate witness')

    def test_four_edge_closed_walk_is_not_six_divisible(self):
        """P1-09: even H1 length does not imply multiples of six or admission."""
        report = evaluate(self.fixture, self.ledger)
        self.assertEqual(report['q4_directed_edges_checked'], 64)
        counterexample = report['four_edge_counterexample']
        self.assertEqual(counterexample['traversals'], 4)
        self.assertFalse(counterexample['multiple_of_six'])
        self.assertEqual(counterexample['native_admission'], 'not_asserted')

    def test_all_fixture_and_ledger_statuses_reject_promotion_or_omission(self):
        """P5-06: all four consumed status fields are enforced on both inputs."""
        for filename in ('two_square_fold.json', 'event_ledger.json'):
            for field in ('status', 'admission_status', 'native_execution_status', 'empirical_status'):
                with self.subTest(filename=filename, field=field):
                    self.mutated_rejection(filename, lambda f, k=field: f.update({k: 'PASS'}),
                                           'Unsupported or missing fixture status: ' + field)
                    self.mutated_rejection(filename, lambda f, k=field: f.pop(k),
                                           'Unsupported or missing fixture status: ' + field)

    def test_count_types_and_undeclared_certificates_reject(self):
        self.mutated_rejection('event_ledger.json', lambda f: f.update(repetitions=True),
                               'Repetition count must be an integer')
        self.mutated_rejection('event_ledger.json', lambda f: f['events'][0].update(ordinal=1.0),
                               'ordinal: expected exact integer')
        self.mutated_rejection('event_ledger.json', lambda f: f.update(fusion_certificate='forged'),
                               'Event ledger: missing or unsupported fields')

    def test_persisted_report_corruption_rejects_read_only(self):
        """P5-04/P5-06: verifier never repairs corrupted generated evidence."""
        self.mutated_rejection('folding_report.json', lambda f: f.update(native_admission='admitted'),
                               'Persisted folding report differs')

    def test_unknown_cli_flag_rejects(self):
        frozen = snapshot(self.root)
        result = self.cli(extra=('--repair',))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('unrecognized arguments', result.stderr)
        self.assertEqual(snapshot(self.root), frozen)

    def test_explicit_generation_reproduces_outputs(self):
        frozen = snapshot(self.root)
        result = subprocess.run([sys.executable, '-B', str(GENERATE), '--root', str(self.root)],
                                capture_output=True, text=True, timeout=30)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(snapshot(self.root), frozen)
        self.assertEqual(verify(self.root)['native_admission'], 'not_asserted')

    def test_generation_to_disposable_output_preserves_source(self):
        """P5-04: separate output generation reads but never edits its input root."""
        frozen = snapshot(self.root)
        with tempfile.TemporaryDirectory(prefix='matter1-folding-output-') as tmp:
            destination = Path(tmp)
            result = subprocess.run([sys.executable, '-B', str(GENERATE), '--root', str(self.root),
                                     '--output-root', str(destination)],
                                    capture_output=True, text=True, timeout=30)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(snapshot(self.root), frozen)
            inventory = snapshot(destination)
            expected = {str(DATA / name): frozen[str(DATA / name)]
                        for name in ('event_ledger.json', 'folding_report.json')}
            self.assertEqual(inventory, expected, 'Only deterministic generated files belong in output')


if __name__ == '__main__':
    unittest.main()
